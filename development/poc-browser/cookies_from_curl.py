#!/usr/bin/env python3
# Turn a DevTools "Copy as cURL" (or a bare "Cookie:" header, or "k=v; k=v")
# into a Netscape cookies.txt scoped to --host.
#
# WHY this beats the alternatives: the browser sends EVERY cookie — HttpOnly
# (sid, mybbuser) AND in-memory session cookies — in each request's Cookie
# header. `document.cookie` can't see HttpOnly; `cookies.sqlite` can't see
# session cookies. The request header has them all. One copy, no per-cookie work.
#
#   DevTools > Network > reload the onion > right-click a request to the onion
#   host > Copy > Copy as cURL, then:
#     xclip -o -sel clip | python cookies_from_curl.py --host <onion-host> > warmed.cookies.txt
#   (or save the blob to a file and pass -i curl.txt)
from __future__ import annotations

import argparse
import re
import sys
import time


def extract_cookie_string(blob: str) -> str:
    """Pull the cookie string out of a cURL blob / header line / raw pairs."""
    # curl -b '...' / --cookie '...'
    m = re.search(r"(?:-b|--cookie)\s+(['\"])(.*?)\1", blob, re.S)
    if m:
        return m.group(2)
    # curl -H 'cookie: ...' (header name case-insensitive)
    m = re.search(r"-H\s+(['\"])\s*cookie:\s*(.*?)\1", blob, re.S | re.I)
    if m:
        return m.group(2)
    # a raw "Cookie: ..." header line
    m = re.search(r"^\s*cookie:\s*(.+)$", blob, re.M | re.I)
    if m:
        return m.group(1).strip()
    # already just "k=v; k=v"
    if "=" in blob and ";" in blob:
        return blob.strip()
    return ""


def to_netscape(cookie_string: str, host: str, *, ttl_days: int = 365) -> list[str]:
    host = re.sub(r"^https?://", "", host).split("/")[0].strip()
    if not host:
        raise ValueError("empty host")
    expiry = int(time.time()) + 86400 * ttl_days  # keep the warmed session alive
    lines = ["# Netscape HTTP Cookie File", "# generated by poc-browser/cookies_from_curl.py"]
    n = 0
    for part in cookie_string.split(";"):
        part = part.strip()
        if "=" not in part:
            continue
        name, val = part.split("=", 1)
        name, val = name.strip(), val.strip()
        if not name:
            continue
        # host-only cookie (col2 FALSE), path /, secure FALSE (onion is http).
        lines.append(f"{host}\tFALSE\t/\tFALSE\t{expiry}\t{name}\t{val}")
        n += 1
    if n == 0:
        raise ValueError("parsed 0 cookies")
    return lines


def _selftest() -> None:
    curl = """curl 'http://x.onion/index.php' -X GET \\
      -H 'User-Agent: Mozilla/5.0' \\
      -H 'cookie: mybb[lastvisit]=1790; sid=139d23; mybbuser=768203_qGqIb' \\
      --compressed"""
    assert extract_cookie_string(curl) == "mybb[lastvisit]=1790; sid=139d23; mybbuser=768203_qGqIb"
    assert extract_cookie_string("Cookie: a=1; b=2") == "a=1; b=2"
    assert extract_cookie_string("a=1; b=2") == "a=1; b=2"
    assert extract_cookie_string("curl 'http://x' -b 'z=9; q=8'") == "z=9; q=8"
    out = to_netscape("sid=139d23; mybbuser=768203", "pwnfrm7rbf.onion")
    body = [l for l in out if not l.startswith("#")]
    assert len(body) == 2, body
    assert body[0].split("\t") == ["pwnfrm7rbf.onion", "FALSE", "/", "FALSE", body[0].split("\t")[4], "sid", "139d23"]
    print("OK  cookies_from_curl selftest: cURL/header/raw extraction + Netscape emit")


def main() -> None:
    ap = argparse.ArgumentParser(description="Copy-as-cURL -> Netscape cookies.txt")
    ap.add_argument("--host", help="cookie host (the onion, no scheme)")
    ap.add_argument("-i", "--input", help="file with the cURL/header blob (default: stdin)")
    ap.add_argument("--ttl-days", type=int, default=365)
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        _selftest()
        return
    if not a.host:
        sys.exit("--host is required (the onion host)")
    blob = open(a.input, encoding="utf-8").read() if a.input else sys.stdin.read()
    cs = extract_cookie_string(blob)
    if not cs:
        sys.exit("no Cookie found — paste a 'Copy as cURL' blob, a 'Cookie:' header, or 'k=v; k=v'.")
    lines = to_netscape(cs, a.host, ttl_days=a.ttl_days)
    sys.stderr.write(f"[ok] {len(lines) - 2} cookies -> {re.sub(r'^https?://', '', a.host).split('/')[0]}\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
